import assert from 'node:assert/strict';
import { installDom, importUi } from './helpers/jsdom_env.mjs';
installDom({ mode: 'cloud' });
const { remoteRemoveWaitAllowed: allowed, HUB_REMOVE_WAIT_DEPLOYED, removeWaitRequest } = await importUi('remove_wait_policy');
const owner = { id: 'owned', owner: true, status: 'online', coral_version: '2.0.60' };
assert.equal(HUB_REMOVE_WAIT_DEPLOYED, false, 'batch-127 has not been declared deployed');
assert.equal(allowed('owned', [owner], { cloud: true }), false, 'production stays off even for an eligible owner');
const check = (row, context = {}) => allowed('owned', [row], { cloud: true, deployed: true, ...context });
assert.equal(check(owner), true, 'explicit owner at the protocol floor after deployment');
for (const value of [undefined, null, false, 'true', 1]) assert.equal(check({ ...owner, owner: value }), false, 'unknown/malformed ownership is never inferred');
for (const version of ['', 'garbage', '2.0.59', '2.0.60-rc.1']) assert.equal(check({ ...owner, coral_version: version }), false, 'unknown/older/pre-release protocol refused');
assert.equal(check({ ...owner, coral_version: 'v2.0.61+build' }), true);
assert.equal(check({ ...owner, status: 'offline' }), false);
assert.equal(check(owner, { cloud: false }), false, 'self-hosted remote keys are not the signed-in owner');
assert.equal(check(owner, { deployed: false }), false);
assert.equal(check(owner, { deployed: 'true' }), false);
assert.equal(allowed('missing', [owner], { cloud: true, deployed: true }), false);
assert.equal(allowed('local', [{ ...owner, id: 'local' }], { cloud: true, deployed: true }), false, 'the Hub is not a computer');
const request = removeWaitRequest({ name: 'Same/name', session_id: 'session-2', agent_type: 'claude' }, 'owned');
assert.equal(request.server, 'owned', 'the selected computer is retained');
assert.equal(request.path, '/api/sessions/live/Same%2Fname/dismiss-wait');
assert.deepEqual(JSON.parse(request.options.body), { session_id: 'session-2', agent_type: 'claude', remove: true });
assert.equal(request.options.method, 'POST');
const { canRemoveWait } = await importUi('dismiss_wait');
const { state } = await importUi('state');
state.servers = [owner];
assert.equal(canRemoveWait({ name: 'Remote', server: 'owned', session_id: 'remote-1', agent_type: 'claude', waiting_for_input: true, wait_ignored: true, waiting_kind: 'permission', waiting_since: '2026-11-08T00:00:00Z' }), false, 'actual UI eligibility cannot bypass the deployment gate');
console.log('PASS remote removal owner/version/deployment gates and exact wire contract; production disabled');
process.exit(0);
