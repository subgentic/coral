func TestTaskTextVersionsAndRestore(t *testing.T) {
	s := testStore(t)
	ctx := context.Background()
	task, err := s.CreateTask(ctx, "team", "First title", "Original body", "medium", "creator")
	require.NoError(t, err)
	require.Equal(t, 1, task.Version)
	title, priority := "Second title", "high"
	next, err := s.EditTaskText(ctx, "team", task.ID, "creator", &title, &priority, 0, 1)
	require.NoError(t, err)
	require.Equal(t, 2, next.Version)
	history, err := s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Len(t, history, 2)
	require.Equal(t, "First title", history[0].Snapshot.Title)
	require.Equal(t, "creator", history[1].Editor)
	require.Equal(t, "First title", history[1].Changes["title"].Before)
	_, err = s.EditTaskText(ctx, "team", task.ID, "creator", &title, nil, 0, 1)
	require.ErrorContains(t, err, "changed to v2")
	restored, err := s.EditTaskText(ctx, "team", task.ID, "creator", nil, nil, 1, 2)
	require.NoError(t, err)
	require.Equal(t, 3, restored.Version)
	require.Equal(t, "First title", restored.Title)
	require.Equal(t, "medium", restored.Priority)
	history, err = s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Len(t, history, 3)
	require.Equal(t, "Second title", history[1].Snapshot.Title)
	_, err = s.TaskHistory(ctx, "another", task.ID)
	require.Error(t, err)
	_, err = s.CancelTask(ctx, "team", task.ID, "creator", nil)
	require.NoError(t, err)
	_, err = s.EditTaskText(ctx, "team", task.ID, "creator", &title, nil, 0, 3)
	require.ErrorContains(t, err, "cannot be edited")
	history, err = s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Len(t, history, 3, "a refused edit adds no version")
	done, err := s.CreateTask(ctx, "team", "Done", "", "medium", "creator", "worker")
	require.NoError(t, err)
	_, err = s.ClaimTask(ctx, "team", "worker", done.ID)
	require.NoError(t, err)
	_, err = s.CompleteTask(ctx, "team", done.ID, "worker", nil)
	require.NoError(t, err)
	_, err = s.EditTaskText(ctx, "team", done.ID, "creator", &title, nil, 0, 1)
	require.ErrorContains(t, err, "cannot be edited")
}

func TestTaskTextEditMakesOlderApprovalStale(t *testing.T) {
	s := testStore(t)
	ctx := context.Background()
	for _, who := range []string{"Orchestrator", "QA1", "QA2"} {
		_, err := s.Subscribe(ctx, "team", who, who, who+"-session", nil, "all")
		require.NoError(t, err)
	}
	task, err := s.CreateTask(ctx, "team", "Before", "", "medium", "creator", "worker")
	require.NoError(t, err)
	_, err = s.ClaimTask(ctx, "team", "worker", task.ID)
	require.NoError(t, err)
	_, err = s.SubmitCompletionReview(ctx, "team", task.ID, "worker", "done", "success", "please review", nil)
	require.NoError(t, err)
	_, _, err = s.HandToOrchestrator(ctx, "team", task.ID, "worker")
	require.NoError(t, err)
	_, _, err = s.DelegateReview(ctx, "team", task.ID, "Orchestrator", []string{"QA1", "QA2"})
	require.NoError(t, err)
	verdict, err := s.ApproveReview(ctx, "team", task.ID, "QA1", "read v1", 1)
	require.NoError(t, err)
	require.False(t, verdict.Complete)
	title := "After"
	edited, err := s.EditTaskText(ctx, "team", task.ID, "creator", &title, nil, 0, 1)
	require.NoError(t, err)
	me := edited.Workflow.ReviewRounds[0].Reviewers[0]
	require.Equal(t, "stale", me.State)
	require.Equal(t, 1, me.TaskVersion)
	require.Len(t, me.PreviousTextApprovals, 1)
	require.Equal(t, 1, me.PreviousTextApprovals[0].Version)
	rt, err := s.GetTask(ctx, "team", me.ReviewTaskID)
	require.NoError(t, err)
	require.Equal(t, "pending", rt.Status)
	require.Empty(t, rt.Workflow.Outcome)
	_, err = s.ApproveReviewTextVersion(ctx, "team", task.ID, "QA1", "old", 1, NoRevisionStated, 1)
	require.ErrorContains(t, err, "changed to v2")
	verdict, err = s.ApproveReviewTextVersion(ctx, "team", task.ID, "QA2", "new", 1, NoRevisionStated, 2)
	require.NoError(t, err)
	require.False(t, verdict.Complete)
	verdict, err = s.ApproveReviewTextVersion(ctx, "team", task.ID, "QA1", "reread", 1, NoRevisionStated, 2)
	require.NoError(t, err)
	require.True(t, verdict.Complete)
	require.Equal(t, 2, verdict.Task.Workflow.ReviewRounds[0].Reviewers[0].TaskVersion)
}

func TestTaskTextLegacyBaselineIsMarkedAndNotRewritten(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "legacy.db")
	s, err := NewStoreWithKey(path, "")
	require.NoError(t, err)
	task, err := s.CreateTask(ctx, "team", "Current legacy text", "body", "medium", "creator")
	require.NoError(t, err)
	_, err = s.db.ExecContext(ctx, "DROP TRIGGER task_initial_version; DROP TABLE task_versions;")
	require.NoError(t, err)
	require.NoError(t, s.Close())
	s, err = NewStoreWithKey(path, "")
	require.NoError(t, err)
	history, err := s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Len(t, history, 1)
	require.Equal(t, "Migration", history[0].Editor)
	require.Equal(t, "Current legacy text", history[0].Snapshot.Title)
	original := history[0]
	require.NoError(t, s.Close())
	s, err = NewStoreWithKey(path, "")
	require.NoError(t, err)
	defer s.Close()
	history, err = s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Equal(t, original, history[0], "reopening must not rewrite the imported baseline")
}

func TestTaskTextInstructionsAreVersionedAndRestored(t *testing.T) {
	s := testStore(t)
	ctx := context.Background()
	task, err := s.CreateTask(ctx, "team", "Instructions", "body", "medium", "creator")
	require.NoError(t, err)
	original := task.Workflow.EffectiveInstructions
	amended, err := s.AmendTask(ctx, "team", task.ID, "creator", 1, "Correct instructions", map[string]interface{}{"workflow_instructions": "Use fixture B."})
	require.NoError(t, err)
	require.Equal(t, 2, amended.Version)
	history, err := s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Equal(t, original, history[0].Snapshot.Instructions)
	require.Contains(t, history[1].Snapshot.Instructions, "Use fixture B.")
	require.Equal(t, original, history[1].Changes["instructions"].Before)
	restored, err := s.EditTaskText(ctx, "team", task.ID, "creator", nil, nil, 1, 2)
	require.NoError(t, err)
	require.Equal(t, 3, restored.Version)
	require.Equal(t, original, restored.Workflow.EffectiveInstructions)
	require.Equal(t, 3, restored.Revision)
	again, err := s.AmendTask(ctx, "team", task.ID, "creator", 3, "Next correction", map[string]interface{}{"workflow_instructions": "Use fixture C."})
	require.NoError(t, err)
	require.Equal(t, 4, again.Version)
	require.Contains(t, again.Workflow.EffectiveInstructions, "Use fixture C.")
	require.NotContains(t, again.Workflow.EffectiveInstructions, "Use fixture B.")
	history, err = s.TaskHistory(ctx, "team", task.ID)
	require.NoError(t, err)
	require.Equal(t, original, history[0].Snapshot.Instructions, "v1 stays immutable")
	require.Contains(t, history[1].Snapshot.Instructions, "Use fixture B.")
}
